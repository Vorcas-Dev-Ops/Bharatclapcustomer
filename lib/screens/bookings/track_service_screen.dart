                      child: const Icon(Icons.call, color: Colors.white, size: 18),
                    ),
                  ),
                ],
              ),
            ],
          ),
        ],
      ),
    );
  }

  Widget _buildTimeline({
    required int currentStep,
    required String status,
    String? startOtp,
    String? endOtp,
  }) {
    final bool showStartOtpBox = (status == 'arrived' || status == 'waiting_start_otp');
    final bool showEndOtpBox = (status == 'waiting_end_otp');

    final bookingCode = _bookingData?['booking_id']?.toString() ?? _bookingData?['_id']?.toString() ?? '';

    return ListView(
      shrinkWrap: true,
      physics: const NeverScrollableScrollPhysics(),
      children: [
        _buildTimelineItem(
          index: 0,
          currentStep: currentStep,
          status: status,
          title: 'Booking Placed',
          subtitle: bookingCode.isNotEmpty ? 'Order confirmed (Ref: $bookingCode)' : 'Order confirmed successfully',
          isLast: false,
        ),
        _buildTimelineItem(
          index: 1,
          currentStep: currentStep,
          status: status,
          title: 'Professional Assigned',
          subtitle: currentStep >= 1 ? 'Provider has accepted your booking' : 'Searching for professional...',
          isLast: false,
        ),
        _buildTimelineItem(
          index: 2,
          currentStep: currentStep,
          status: status,
          title: 'Professional On The Way',
          subtitle: currentStep >= 2 ? 'Provider is traveling to your location' : 'Waiting for provider movement',
          isLast: false,
        ),
        _buildTimelineItem(
          index: 3,
          currentStep: currentStep,
          status: status,
          title: 'Professional Arrived & Start Service',
          subtitle: showStartOtpBox
              ? 'Share this Start OTP with the professional upon arrival'
              : (currentStep > 3 ? 'Start OTP Verified' : 'OTP generated when provider arrives'),
          isLast: false,
          child: showStartOtpBox
              ? _buildOtpBox(
                  otp: startOtp,
                  helperText: 'Provide this Start OTP to the professional to begin service.',
                )
              : null,
        ),
        _buildTimelineItem(
          index: 4,
          currentStep: currentStep,
          status: status,
          title: 'Service In Progress',
          subtitle: currentStep >= 4 ? 'Professional is executing your service' : 'Pending service start',
          isLast: false,
        ),
        _buildTimelineItem(
          index: 5,
          currentStep: currentStep,
          status: status,
          title: 'Service Completion Verification',
          subtitle: showEndOtpBox
              ? 'Share this End OTP with the professional to finish service'
              : (currentStep > 5 ? 'End OTP Verified' : 'OTP generated when service ends'),
          isLast: false,
          child: showEndOtpBox
              ? _buildOtpBox(
                  otp: endOtp ?? _bookingData?['endOtp'] ?? _bookingData?['completionOtp'],
                  helperText: 'Provide this End OTP ONLY after service is completed satisfactorily.',
                  isEndOtp: true,
                  bookingId: (widget.bookingId ?? _bookingData?['_id'] ?? _bookingData?['id'])?.toString(),
                )
              : null,
        ),
        _buildTimelineItem(
          index: 6,
          currentStep: currentStep,
          status: status,
          title: 'Service Completed',
          subtitle: status == 'completed' ? 'Service fulfilled successfully' : 'Final step',
          isLast: true,
        ),
      ],
    );
  }

  Widget _buildOtpBox({
    required String? otp,
    required String helperText,
    bool isEndOtp = false,
    String? bookingId,
  }) {
    final String formattedOtp = (otp != null && otp.length == 6)
        ? '${otp[0]}  ${otp[1]}  ${otp[2]}  ${otp[3]}  ${otp[4]}  ${otp[5]}'
        : (otp ?? 'Waiting for OTP...');

    return Container(
      margin: const EdgeInsets.only(top: 12, bottom: 8),
      padding: const EdgeInsets.all(16),
      width: double.infinity,
      decoration: BoxDecoration(
        color: Colors.white,
        border: Border.all(color: const Color(0xFF1B1464).withOpacity(0.3), width: 1.5),
        borderRadius: BorderRadius.circular(12),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withOpacity(0.04),
            blurRadius: 6,
            offset: const Offset(0, 3),
          ),
        ],
      ),
      child: Column(
        children: [
          Text(
            formattedOtp,
            style: const TextStyle(
              fontSize: 26,
              fontWeight: FontWeight.bold,
              color: Color(0xFF1B1464),
              letterSpacing: 4.0,
            ),
          ),
          const SizedBox(height: 8),
          Text(
            helperText,
            textAlign: TextAlign.center,
            style: TextStyle(
              fontSize: 11,
              color: Colors.grey.shade600,
              fontWeight: FontWeight.w500,
            ),
          ),
          if (isEndOtp && bookingId != null) ...[
            const SizedBox(height: 12),
            OutlinedButton.icon(
              style: OutlinedButton.styleFrom(
                foregroundColor: const Color(0xFF1B1464),
                side: const BorderSide(color: Color(0xFF1B1464)),
                shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(8)),
                padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
              ),
              icon: const Icon(Icons.send_to_mobile, size: 16),
              label: const Text('Resend Completion OTP to SMS', style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold)),
              onPressed: () async {
                final res = await ApiService.resendCompletionOtp(bookingId);
                if (mounted) {
                  ScaffoldMessenger.of(context).showSnackBar(
                    SnackBar(
                      content: Text(res['message'] ?? 'Resent completion OTP!'),
                      backgroundColor: res['success'] == true ? Colors.green : Colors.red,
                    ),
                  );
                }
              },
            ),
          ],
        ],
      ),
    );
  }


  Widget _buildTimelineItem({
    required int index,
    required int currentStep,
    required String status,
    required String title,
    required String subtitle,
    required bool isLast,
    Widget? child,
  }) {
    bool isCompleted = index < currentStep || (status == 'completed' && index <= currentStep);
    bool isActive = index == currentStep && status != 'completed';

    Color lineColor = isCompleted ? const Color(0xFF1B1464) : Colors.grey.shade200;
    Color titleColor = isCompleted || isActive ? Colors.black87 : Colors.grey.shade400;
    Color subtitleColor = isCompleted || isActive ? Colors.grey.shade600 : Colors.grey.shade400;

    return Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Column(
          children: [
            Container(
              width: 24,
              height: 24,
              decoration: BoxDecoration(
                color: isCompleted ? const Color(0xFF1B1464) : (isActive ? Colors.white : Colors.grey.shade300),
                shape: BoxShape.circle,
                border: Border.all(
                  color: isActive ? const Color(0xFF1B1464) : Colors.transparent,
                  width: 2,
                ),
              ),
              child: isCompleted
                  ? const Icon(Icons.check, size: 14, color: Colors.white)
                  : (isActive
                      ? Center(
                          child: Container(
                            width: 8,
                            height: 8,
                            decoration: const BoxDecoration(
                              color: Color(0xFF1B1464),
                              shape: BoxShape.circle,
                            ),
                          ),
                        )
                      : null),
            ),
            if (!isLast)
              Container(
                width: 2,
                height: child != null ? 100 : 48,
                color: lineColor,
              ),
          ],
        ),
        const SizedBox(width: 12),
        Expanded(
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text(
                title,
                style: TextStyle(
                  fontSize: 15,
                  fontWeight: FontWeight.bold,
                  color: titleColor,
                ),
              ),
              if (subtitle.isNotEmpty) ...[
                const SizedBox(height: 2),
                Text(
                  subtitle,
                  style: TextStyle(
                    fontSize: 12,
                    color: subtitleColor,
                  ),
                ),
              ],
              if (child != null) child,
              const SizedBox(height: 16),
            ],
          ),
        ),
      ],
    );
  }
